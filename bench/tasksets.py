HUMANEVAL_BRIEF = (
    "Complete this Python function. Reply with the complete function in a ```python block, "
    "including the imports and any helper functions from the code below that it uses.\n\n"
    "```python\n{prompt}\n```"
)

# Runs inside the check sandbox after the worker's code is loaded. The reference solution and
# the inputs travel base64-encoded so their identifiers never look like calls in the check text.
_CHECK = '''
import base64 as _b64, copy as _copy, json as _json, math as _math

_ENTRY = {entry!r}
_ATOL = {atol!r}
_ref_ns = {{}}
exec(_b64.b64decode({ref!r}).decode(), _ref_ns)
_ref = _ref_ns[_ENTRY]
_cand = {entry}
_INPUTS = _json.loads(_b64.b64decode({inputs!r}).decode())


def _show(x, n=120):
    s = repr(x)
    return s if len(s) <= n else s[:n] + "..."


def _is_floats(x):
    return isinstance(x, float) or (isinstance(x, (list, tuple)) and len(x) > 0 and all(isinstance(v, float) for v in x))


def _close(a, b, tol):
    if isinstance(a, float) and isinstance(b, float) and _math.isnan(a) and _math.isnan(b):
        return True
    return isinstance(a, (int, float)) and not isinstance(a, bool) and _math.isclose(a, b, rel_tol=1e-7, abs_tol=tol)


def _same(got, want):
    tol = _ATOL or (1e-6 if _is_floats(want) else 0)
    if not tol:
        return got == want
    if isinstance(want, (list, tuple)):
        return isinstance(got, (list, tuple)) and len(got) == len(want) and all(_close(g, w, tol) for g, w in zip(got, want))
    return _close(got, want, tol)


for _i, _args in enumerate(_INPUTS):
    try:
        _want = _ref(*_copy.deepcopy(_args))
    except Exception:
        continue  # not a valid input for the reference either
    _call = f"{{_ENTRY}}({{', '.join(_show(a, 60) for a in _args)}})"
    try:
        _got = _cand(*_copy.deepcopy(_args))
    except Exception as _e:
        raise AssertionError(f"{{_call}} raised {{type(_e).__name__}}: {{_e}} (input {{_i + 1}} of {{len(_INPUTS)}})") from None
    if _ENTRY == "find_zero":  # any root is accepted, as in EvalPlus
        _ok = isinstance(_got, (int, float)) and abs(_ref_ns["poly"](*_args, _got)) <= (_ATOL or 1e-6)
    else:
        _ok = _same(_got, _want)
    if not _ok:
        raise AssertionError(f"{{_call}} returned {{_show(_got)}}, expected {{_show(_want)}} (input {{_i + 1}} of {{len(_INPUTS)}})")
'''


def _b64(text: str) -> str:
    return base64.b64encode(text.encode()).decode()


def humaneval_check(problem: dict) -> str:
    inputs = problem["base_input"] + problem["plus_input"]
    return _CHECK.format(
        entry=problem["entry_point"],
        atol=problem.get("atol") or 0,
        ref=_b64(problem["prompt"] + problem["canonical_solution"]),
        inputs=_b64(json.dumps(inputs)),
    )


def _download(name: str) -> Path:
    path = DATA_DIR / name
    if path.exists():
        return path
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    url = EVALPLUS_URL.format(name=name)
    error: Exception | None = None
    for attempt in range(6):  # the lab network drops connections; the files are under 1 MB
        try:
            with urllib.request.urlopen(url, timeout=60) as resp:
                data = resp.read()
            part = path.with_suffix(".part")
            part.write_bytes(data)
            part.rename(path)
            return path
        except OSError as e:
            error = e
            time.sleep(3)
    raise SystemExit(f"could not download {url} ({error}). Download it in a browser and put it in {DATA_DIR}/")


def load_tasks(task_set: str, limit: int | None = None) -> list[Task]:
    if task_set == "smoke":
        tasks = list(SMOKE)
    elif task_set in EVALPLUS_FILES:
        with gzip.open(_download(EVALPLUS_FILES[task_set]), "rt") as f:
            problems = [json.loads(line) for line in f]
        tasks = [
            Task(p["task_id"], HUMANEVAL_BRIEF.format(prompt=p["prompt"].strip("\n")), humaneval_check(p),
                 (p["entry_point"],), show_check=False)
            for p in problems
        ]
    else:
        raise SystemExit(f"unknown task set {task_set!r}; choose from {', '.join(TASK_SETS)}")
    return tasks[:limit] if limit else tasks
