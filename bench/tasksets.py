from dataclasses import dataclass
from pathlib import Path

DATA_DIR = Path(__file__).parent / "data"
COMPAT_SOURCE = (Path(__file__).parent / "evalplus_compat.py").read_text()
_HE = "https://github.com/evalplus/humanevalplus_release/releases/download/v0.1.10/"
_MBPP = "https://github.com/evalplus/mbppplus_release/releases/download/v0.2.0/"
# task set -> (dataset, file, download URL)
EVALPLUS_SETS = {
    "humaneval+": ("humaneval", "HumanEvalPlus.jsonl.gz", _HE + "HumanEvalPlus.jsonl.gz"),
    "humaneval+mini": ("humaneval", "HumanEvalPlus-Mini.jsonl.gz", _HE + "HumanEvalPlus-Mini.jsonl.gz"),
    "mbpp+": ("mbpp", "MbppPlus.jsonl.gz", _MBPP + "MbppPlus.jsonl.gz"),
}
TASK_SETS = ("smoke", *EVALPLUS_SETS)


@dataclass(frozen=True)
class Task:
    name: str
    prompt: str
    check: str
    targets: tuple[str, ...]  # functions the check needs; if one is undefined, it's a format failure
    show_check: bool = True


