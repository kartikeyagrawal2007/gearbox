"""Task sets for bench/false_done.py.

- smoke: 8 hand-written tasks. The worker sees each check as its spec. A quick pipeline test.
- humaneval+: the 164 HumanEval problems with EvalPlus's extended tests (~760 inputs per
  problem; Liu et al., "Is Your Code Generated by ChatGPT Really Correct?", NeurIPS 2023).
- humaneval+mini: the same problems with EvalPlus's reduced test set (~17 inputs each).

HumanEval+ checks are hidden from the worker, as in the official evaluation: it sees only
the prompt (signature and docstring). Each check runs EvalPlus's reference solution on every
input and compares outputs under the same rules: float tolerance, a special case for
find_zero, and inputs deep-copied so a solution can't mutate them for the next call.
Data: github.com/evalplus/humanevalplus_release (Apache-2.0), downloaded on first use.
"""

from __future__ import annotations

import base64
import gzip
import json
import time
import urllib.request
from dataclasses import dataclass
from pathlib import Path

DATA_DIR = Path(__file__).parent / "data"
EVALPLUS_URL = "https://github.com/evalplus/humanevalplus_release/releases/download/v0.1.10/{name}"
EVALPLUS_FILES = {"humaneval+": "HumanEvalPlus.jsonl.gz", "humaneval+mini": "HumanEvalPlus-Mini.jsonl.gz"}
TASK_SETS = ("smoke", *EVALPLUS_FILES)


@dataclass(frozen=True)
class Task:
    name: str
    prompt: str
    check: str
    targets: tuple[str, ...]  # functions the check needs; if one is undefined, it's a format failure
    show_check: bool = True


