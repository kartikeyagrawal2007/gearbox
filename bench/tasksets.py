"""Task sets for bench/false_done.py.

- smoke: 8 hand-written tasks. The worker sees each check as its spec. A quick pipeline test.
- humaneval+: the 164 HumanEval problems with EvalPlus's extended tests (~760 inputs per
  problem; Liu et al., "Is Your Code Generated by ChatGPT Really Correct?", NeurIPS 2023).
- humaneval+mini: the same problems with EvalPlus's reduced test set (~17 inputs each).
- mbpp+: 378 MBPP problems with EvalPlus's extended tests (~105 inputs each).

EvalPlus checks are hidden from the worker, as in the official evaluation: it sees only the
prompt. Each check runs EvalPlus's reference solution on every input and grades the worker's
output with the official rules: exact match, float tolerance only for same-typed outputs,
the special oracles (find_zero, set-equality and not-None tasks, ...), MBPP input conversion,
and inputs deep-copied so a solution can't mutate them for the next call. The rules and
conversions come verbatim from EvalPlus via bench/evalplus_compat.py.
Data: github.com/evalplus/{humanevalplus,mbppplus}_release (Apache-2.0), downloaded on first use.
"""

