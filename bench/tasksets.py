# Runs inside the check sandbox after the worker's code is loaded. The reference solution,
# EvalPlus's compat code and the inputs travel base64-encoded, so their identifiers never look
# like the worker's own names in the check text.
_CHECK = '''
import base64 as _b64, copy as _copy, json as _json

_DATASET, _TASK_ID, _ENTRY, _ATOL = {dataset!r}, {task_id!r}, {entry!r}, {atol!r}
_compat = {{}}
exec(_b64.b64decode({compat!r}).decode(), _compat)
_ref_ns = {{}}
exec(_b64.b64decode({ref!r}).decode(), _ref_ns)
_ref = _ref_ns[_ENTRY]
_cand = {entry}
_INPUTS = _json.loads(_b64.b64decode({inputs!r}).decode())
if _DATASET == "mbpp":
    _INPUTS = _compat["mbpp_deserialize_inputs"](_TASK_ID, _INPUTS)


def _show(x, n=120):
    s = repr(x)
    return s if len(s) <= n else s[:n] + "..."


def _is_floats(x):  # as evalplus.eval.is_floats
    return isinstance(x, float) or (isinstance(x, (list, tuple)) and len(x) > 0 and all(isinstance(i, float) for i in x))


def _allclose(a, b, atol):  # numpy.allclose(a, b, rtol=1e-07, atol=atol), without numpy
    if isinstance(b, (list, tuple)):
        return isinstance(a, (list, tuple)) and len(a) == len(b) and all(_allclose(x, y, atol) for x, y in zip(a, b))
    try:
        return abs(a - b) <= atol + 1e-07 * abs(b)
    except TypeError:
        return False


def _judge(out, exp, inp):  # mirrors evalplus.eval.unsafe_execute
    if _DATASET == "humaneval" and _ENTRY == "find_zero":
        try:
            return abs(_compat["_poly"](*inp, out)) <= _ATOL
        except Exception:
            return False
    try:
        exact = bool(out == exp)
    except Exception:
        exact = False
    if _DATASET == "mbpp":
        if _ENTRY == "are_equivalent":
            exact = True
        elif _ENTRY == "sum_div":
            exact = exact or out == 0
        elif _ENTRY == "surface_Area":
            exact = exact or abs(out - _compat["_surface_Area"](*inp)) <= _ATOL
        elif _ENTRY == "digit_distance_nums":
            exact = exact or out == _compat["_digit_distance_nums"](*inp)
        elif _ENTRY in _compat["MBPP_OUTPUT_SET_EQ_TASKS"]:
            exact = set(out) == set(exp)
        elif _ENTRY in _compat["MBPP_OUTPUT_NOT_NONE_TASKS"]:
            exact = out == exp if isinstance(out, bool) else exp == (out is not None)
    atol = _ATOL
    if atol == 0 and _is_floats(exp):
        atol = 1e-6
    if not exact and atol != 0:
        if type(out) != type(exp):
            return False
        if isinstance(exp, (list, tuple)) and len(out) != len(exp):
            return False
        return _allclose(out, exp, atol)
    return exact


_NOT_NONE = _DATASET == "mbpp" and _ENTRY in _compat["MBPP_OUTPUT_NOT_NONE_TASKS"]

for _i, _args in enumerate(_INPUTS):
    try:
        _want = _ref(*_copy.deepcopy(_args))
    except Exception:
        continue  # not a valid input for the reference either
    if _NOT_NONE:  # EvalPlus stores the ground truth for these as "is not None"
        _want = _want is not None
    _call = f"{{_ENTRY}}({{', '.join(_show(a, 60) for a in _args)}})"
    try:
        _got = _cand(*_copy.deepcopy(_args))
    except Exception as _e:
        raise AssertionError(f"{{_call}} raised {{type(_e).__name__}}: {{_e}} (input {{_i + 1}} of {{len(_INPUTS)}})") from None
    try:
        _ok = _judge(_got, _want, _args)
    except Exception:
        _ok = False
    if not _ok:
        raise AssertionError(f"{{_call}} returned {{_show(_got)}}, expected {{_show(_want)}} (input {{_i + 1}} of {{len(_INPUTS)}})")
'''


def _b64(text: str) -> str:
    return base64.b64encode(text.encode()).decode()


def evalplus_check(problem: dict, dataset: str, inputs: list | None = None) -> str:
    """The official base + plus tests, or only `inputs` (a weaker check, for bench/weak_checks.py)."""
    reference = problem["prompt"] + problem["canonical_solution"] if dataset == "humaneval" else problem["canonical_solution"]
    if inputs is None:
        # Mbpp/793 stores its (empty) plus inputs as {} rather than []
        inputs = list(problem["base_input"]) + list(problem["plus_input"] or [])
    return _CHECK.format(
        dataset=dataset,
        task_id=problem["task_id"],
        entry=problem["entry_point"],
        atol=problem.get("atol") or 0,
        compat=_b64(COMPAT_SOURCE),
        ref=_b64(reference),
        inputs=_b64(json.dumps(inputs)),
    )


def humaneval_check(problem: dict) -> str:
    return evalplus_check(problem, "humaneval")


def _download(name: str, url: str) -> Path:
    path = DATA_DIR / name
    if path.exists():
        return path
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    error: Exception | None = None
    for attempt in range(6):  # the lab network drops connections; the files are under 1 MB
        try:
            with urllib.request.urlopen(url, timeout=60) as resp:
                data = resp.read()
            part = path.with_suffix(".part")
            part.write_bytes(data)
            part.rename(path)
            return path
        except OSError as e:
            error = e
            time.sleep(3)
    raise SystemExit(f"could not download {url} ({error}). Download it in a browser and put it in {DATA_DIR}/")


def load_tasks(task_set: str, limit: int | None = None) -> list[Task]:
    if task_set == "smoke":
        tasks = list(SMOKE)
    elif task_set in EVALPLUS_SETS:
        dataset, name, url = EVALPLUS_SETS[task_set]
        with gzip.open(_download(name, url), "rt") as f:
            problems = [json.loads(line) for line in f]
        tasks = [
            Task(p["task_id"], BRIEFS[dataset].format(prompt=p["prompt"].strip("\n"), entry=p["entry_point"]),
                 evalplus_check(p, dataset), (p["entry_point"],), show_check=False)
            for p in problems
        ]
    else:
        raise SystemExit(f"unknown task set {task_set!r}; choose from {', '.join(TASK_SETS)}")
    return tasks[:limit] if limit else tasks
